const assert = require("node:assert/strict")
const fs = require("node:fs")
const vm = require("node:vm")
const context = vm.createContext({Date, isFinite, Number, isNaN})
vm.runInContext(fs.readFileSync("Time.js", "utf8"), context)
const now = new Date(2026, 9, 1, 14, 0).getTime()
const formatted = (y, m, d, h, min) => context.compactDate(new Date(y, m, d, h, min).getTime(), now)
assert.equal(formatted(2026, 9, 1, 10, 30), "Today 10:30 AM")
assert.equal(formatted(2026, 8, 30, 12, 36), "Yesterday 12:36 PM")
assert.equal(formatted(2026, 8, 28, 19, 15), "Monday 7:15 PM")
assert.equal(formatted(2026, 8, 22, 11, 11), "Last Week 11:11 AM")
assert.equal(formatted(2026, 8, 10, 13, 0), "September 10 1:00 PM")
assert.equal(context.compactDate(0, now), "No messages yet")
console.log("time tests passed")
